const BRIDGE_METHODS = new Set(['get_topic', 'find_nodes', 'add_children'])
const bridgeQueue = createQueue()
let bridgeServer: StartedBridge | null = null
let nextBridgeRequestId = 1

type RendererReply = { ok: true; result: unknown } | { ok: false; error: string }

type BridgeWaiter = {
  timer: ReturnType<typeof setTimeout>
  resolve: (reply: RendererReply) => void
}

const bridgeWaiters = new Map<number, BridgeWaiter>()

function isBridgeRecord(value: unknown): value is Record<string, unknown> {
  return value != null && typeof value === 'object' && !Array.isArray(value)
}

function onBridgeResult(value: unknown) {
  if (!isBridgeRecord(value) || typeof value.requestId !== 'number') {
    return
  }
  const waiter = bridgeWaiters.get(value.requestId)
  if (waiter == null) {
    return
  }
  bridgeWaiters.delete(value.requestId)
  clearTimeout(waiter.timer)
  if (value.ok === true) {
    waiter.resolve({ ok: true, result: value.result })
    return
  }
  const error =
    typeof value.error === 'string' && value.error !== '' ? value.error : 'bridge failed'
  waiter.resolve({ ok: false, error })
}

function enrichTopic(win: BrowserWindow, reply: RendererReply): RendererReply {
  if (!reply.ok) {
    return reply
  }
  if (win.isDestroyed() || !isDocumentWindow(win)) {
    return { ok: false, error: 'narr-map has no document window' }
  }
  const body = isBridgeRecord(reply.result) ? reply.result : {}
  return {
    ok: true,
    result: {
      filePath: getDocState(win).filePath,
      rootText: typeof body.rootText === 'string' ? body.rootText : '',
      nodes: Array.isArray(body.nodes) ? body.nodes : []
    }
  }
}

function callDocument(method: string, params: unknown): Promise<RendererReply> {
  const win = getFocusedDocumentWindow()
  if (win == null || win.isDestroyed()) {
    return Promise.resolve({ ok: false, error: 'narr-map has no document window' })
  }
  return new Promise((resolve) => {
    const requestId = nextBridgeRequestId
    nextBridgeRequestId += 1
    const timer = setTimeout(() => {
      if (!bridgeWaiters.has(requestId)) {
        return
      }
      bridgeWaiters.delete(requestId)
      resolve({ ok: false, error: 'timed out' })
    }, 5000)
    bridgeWaiters.set(requestId, {
      timer,
      resolve: (reply) => {
        resolve(method === 'get_topic' ? enrichTopic(win, reply) : reply)
      }
    })
    win.webContents.send('request', 'bridge-request', {
      requestId,
      method,
      params
    })
  })
}

async function handleBridgeRequest(request: BridgeRequest): Promise<BridgeResponse> {
  if (!BRIDGE_METHODS.has(request.method)) {
    return { id: request.id, ok: false, error: `unknown method: ${request.method}` }
  }
  const reply = await callDocument(request.method, request.params ?? {})
  if (reply.ok === false) {
    return { id: request.id, ok: false, error: reply.error }
  }
  return { id: request.id, ok: true, result: reply.result }
}

